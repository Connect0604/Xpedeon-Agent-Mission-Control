    CREATE TABLE [amc].[EXTERNAL_SKILL_PACKAGE_INSTALLS] (
        [ID] NVARCHAR(64) NOT NULL,
        [EXTERNAL_SKILL_PACKAGE_ID] NVARCHAR(64) NOT NULL,
        [VERSION] NVARCHAR(100) NOT NULL,
        [APPROVAL_STATUS] INT NOT NULL,
        [INSTALL_STATUS] INT NOT NULL,
        [PROVISIONED_MCP_SERVER_ID] NVARCHAR(64) NULL,
        [NOTES] NVARCHAR(MAX) NULL,
