IF OBJECT_ID(N'[amc].[EXTERNAL_SKILL_PACKAGES]', N'U') IS NULL
BEGIN
    CREATE TABLE [amc].[EXTERNAL_SKILL_PACKAGES] (
        [ID] NVARCHAR(64) NOT NULL,
        [PACKAGE_KEY] NVARCHAR(255) NOT NULL,
        [NAME] NVARCHAR(255) NOT NULL,
        [VERSION] NVARCHAR(100) NOT NULL,
        [DESCRIPTION] NVARCHAR(MAX) NOT NULL CONSTRAINT [DF_EXTERNAL_SKILL_PACKAGES_DESCRIPTION] DEFAULT (N''),
        [SOURCE_URL] NVARCHAR(2048) NOT NULL,
        [SOURCE_REPO] NVARCHAR(255) NOT NULL,
        [SOURCE_REF] NVARCHAR(255) NOT NULL,
        [MANIFEST_PATH] NVARCHAR(1024) NOT NULL,
        [RAW_SOURCE_URL] NVARCHAR(2048) NOT NULL,
        [KIND] INT NOT NULL CONSTRAINT [DF_EXTERNAL_SKILL_PACKAGES_KIND] DEFAULT (0),
        [CONTENT_HASH] NVARCHAR(128) NOT NULL,
        [MANIFEST_JSON] NVARCHAR(MAX) NOT NULL,
        [RUNTIME_TRANSPORT_TYPE] INT NOT NULL CONSTRAINT [DF_EXTERNAL_SKILL_PACKAGES_RUNTIME_TRANSPORT_TYPE] DEFAULT (3),
        [RUNTIME_ENDPOINT] NVARCHAR(MAX) NOT NULL,
        [REQUIRED_SECRET_NAMES_JSON] NVARCHAR(MAX) NOT NULL CONSTRAINT [DF_EXTERNAL_SKILL_PACKAGES_REQUIRED_SECRETS] DEFAULT (N'[]'),
        [PERMISSION_HINTS_JSON] NVARCHAR(MAX) NOT NULL CONSTRAINT [DF_EXTERNAL_SKILL_PACKAGES_PERMISSION_HINTS] DEFAULT (N'[]'),
        [DECLARED_TOOL_NAMES_JSON] NVARCHAR(MAX) NOT NULL CONSTRAINT [DF_EXTERNAL_SKILL_PACKAGES_DECLARED_TOOLS] DEFAULT (N'[]'),
        [APPROVAL_STATUS] INT NOT NULL CONSTRAINT [DF_EXTERNAL_SKILL_PACKAGES_APPROVAL_STATUS] DEFAULT (0),
        [INSTALL_STATUS] INT NOT NULL CONSTRAINT [DF_EXTERNAL_SKILL_PACKAGES_INSTALL_STATUS] DEFAULT (0),
        [IS_ENABLED] BIT NOT NULL CONSTRAINT [DF_EXTERNAL_SKILL_PACKAGES_IS_ENABLED] DEFAULT (0),
        [IMPORT_ERROR] NVARCHAR(MAX) NULL,
        [LAST_SYNC_AT] DATETIME2 NOT NULL CONSTRAINT [DF_EXTERNAL_SKILL_PACKAGES_LAST_SYNC_AT] DEFAULT (SYSUTCDATETIME()),
        [LAST_HEALTH_CHECK_AT] DATETIME2 NULL,
        [CREATED_AT] DATETIME2 NOT NULL CONSTRAINT [DF_EXTERNAL_SKILL_PACKAGES_CREATED_AT] DEFAULT (SYSUTCDATETIME()),
        [UPDATED_AT] DATETIME2 NOT NULL CONSTRAINT [DF_EXTERNAL_SKILL_PACKAGES_UPDATED_AT] DEFAULT (SYSUTCDATETIME()),
        CONSTRAINT [PK_EXTERNAL_SKILL_PACKAGES] PRIMARY KEY ([ID])
    );
END
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_EXTERNAL_SKILL_PACKAGES_PACKAGE_KEY' AND object_id = OBJECT_ID(N'[amc].[EXTERNAL_SKILL_PACKAGES]'))
BEGIN
    CREATE INDEX [IX_EXTERNAL_SKILL_PACKAGES_PACKAGE_KEY]
        ON [amc].[EXTERNAL_SKILL_PACKAGES] ([PACKAGE_KEY]);
END
GO

